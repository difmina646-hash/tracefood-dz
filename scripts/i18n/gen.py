#!/usr/bin/env python3
"""Builds client/src/i18n/fr.gen.ts and ar.gen.ts from scripts/i18n/part*.txt (key|fr|ar).
Fails if a key used by the code (t('key')) is missing from FR or AR, or defined twice."""
import re, json, pathlib, sys
here = pathlib.Path(__file__).resolve().parent
root = here.parent.parent / 'client' / 'src'
fr, ar = {}, {}
for f in sorted(here.glob('part*.txt')):
    for n, line in enumerate(f.read_text(encoding='utf-8').splitlines(), 1):
        if not line.strip(): continue
        parts = line.split('|')
        if len(parts) != 3: sys.exit(f'{f.name}:{n}: expected key|fr|ar -> {line[:60]}')
        k, a, b = parts
        if k in fr: sys.exit(f'duplicate key {k}')
        fr[k], ar[k] = a, b
def dump(d, name, var):
    body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}' for k, v in sorted(d.items()))
    (root / 'i18n' / name).write_text(f'// generated by scripts/i18n/gen.py from scripts/i18n/part*.txt\nexport const {var}: Record<string, string> = {{\n{body}\n}};\n', encoding='utf-8')
dump(fr, 'fr.gen.ts', 'frGen'); dump(ar, 'ar.gen.ts', 'arGen')
base = set(re.findall(r'"([\w.]+)":\s*"', (root / 'i18n' / 'fr.base.ts').read_text(encoding='utf-8')))
used = set()
for p in root.rglob('*.ts*'):
    if 'i18n' in p.parts: continue
    used |= set(re.findall(r"\bt\('([\w.]+)'", p.read_text(encoding='utf-8')))
missing = sorted(k for k in used if k not in fr and k not in base)
unused = sorted(k for k in fr if k not in used)
print(f'strings={len(fr)} base={len(base)} used_by_code={len(used)}  MISSING={len(missing)}  unused_entries={len(unused)}')
for k in missing: print('  MISSING', k)
for k in unused[:15]: print('  unused', k)
bad = [k for k in fr if set(re.findall(r'\{\{\w+\}\}', fr[k])) != set(re.findall(r'\{\{\w+\}\}', ar[k]))]
print('placeholder mismatches FR/AR:', bad)
sys.exit(1 if missing or bad else 0)
